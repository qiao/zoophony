import { buildPlayer } from '../../../src/models/player.ts';
import { BIND_ROTATIONS } from '../../../src/pose/frames.ts';
import { openLoops, posedPart } from '../../../src/pose/test-clearance.ts';
import { poseSkeleton } from '../../../src/pose/test-kinematics.ts';
const model = buildPlayer('fox-tan', 'flute');
const pose = { rotations: new Float32Array(BIND_ROTATIONS), rootOffset: [0, 0, 0], slideOffset: [0, 0, 0], instrumentOffset: [0, 0, 0], blink: 0 } as never;
const posed = poseSkeleton(model, pose);
const part = posedPart(posed, ['instrument']);
const shells = part.closed?.() ?? [part];
console.log('shells', shells.length, 'triangles', part.triangles.length);
for (const sh of shells) console.log(' shell triangles', sh.triangles.length, 'open loops', openLoops(sh.triangles));
